// Two Truths & a Lie (games/truths.js) against a fresh test server. npm test -- truths
const BASE = process.env.TEST_URL || 'http://localhost:3999';
const { io } = require('socket.io-client');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ✓', m); } else { fail++; console.log('  ✗', m); } };
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
async function until(fn, ms = 5000) { const e = Date.now() + ms; while (Date.now() < e) { try { if (fn()) return true; } catch (x) {} await sleep(30); } console.log('    (timeout)', fn.toString().slice(0, 90)); return false; }

(async () => {
  const mk = (role, o = {}) => {
    const s = io(BASE, { transports: ['websocket'], forceNew: true });
    s.on('arcade', p => { s.last = p; });
    s.on('connect', () => s.emit('register', { role, id: o.id, name: o.name, view: 'arcade' }));
    return s;
  };
  const host = mk('host'), tv = mk('tv');
  const names = ['Ali', 'Bita', 'Cyrus', 'Dara', 'Elham'];
  const P = names.map((n, i) => mk('player', { id: 't' + i, name: n }));
  const byId = Object.fromEntries(P.map((s, i) => ['t' + i, s]));
  await until(() => host.last && host.last.players.filter(p => p.connected).length === 5);
  host.emit('host:setLanguage', 'en');
  host.emit('host:hub:select', { game: 'truths' });
  await until(() => tv.last && tv.last.activeGame === 'truths' && tv.last.game);
  const G = (s) => s.last.game;
  const lines = (i) => [`${names[i]} swam with sharks`, `${names[i]} has three cats`, `${names[i]} met the Pope`];

  console.log('\n# writing lines');
  host.emit('host:truths:start');
  await sleep(200);
  ok(G(host).status === 'lobby', 'no lines written yet: start does nothing');
  const [a, b, c, d, e] = P;
  a.emit('player:truths:write', { lines: ['one', 'two'], lie: 0 });
  a.emit('player:truths:write', { lines: ['one', '  ', 'three'], lie: 0 });
  a.emit('player:truths:write', { lines: ['one', 'two', 'three'], lie: 3 });
  a.emit('player:truths:write', { lines: ['one', 'two', 'three'], lie: 1.5 });
  a.emit('player:truths:write', null);
  await sleep(300);
  ok(!G(a).mySet && !G(tv).ready.length, 'two lines, a blank line, a bad lie index: all rejected');
  a.emit('player:truths:write', { lines: lines(0), lie: 2 });
  b.emit('player:truths:write', { lines: lines(1), lie: 0 });
  c.emit('player:truths:write', { lines: lines(2), lie: 1 });
  await until(() => G(tv).ready.length === 3);
  ok(G(a).mySet && G(a).mySet.lie === 2 && G(a).mySet.lines[2] === lines(0)[2], 'my phone gets my lines back (to edit them)');
  ok(!G(b).mySet || G(b).mySet.lines[0] !== lines(0)[0], 'nobody else gets them');
  ok(!JSON.stringify(G(tv)).includes('sharks') && !JSON.stringify(G(host)).includes('sharks'), 'TV and host see who is ready, not what they wrote');
  a.emit('player:truths:write', { lines: ['x'.repeat(300), 'two', 'three'], lie: 1 });
  await until(() => G(a).mySet.lie === 1);
  ok(G(a).mySet.lines[0].length === 120, 'lines are cut at 120 characters; rewriting replaces');
  a.emit('player:truths:write', { lines: lines(0), lie: 2 });
  await until(() => G(a).mySet.lie === 2);

  console.log('\n# a teller');
  host.emit('host:truths:settings', { askSeconds: 999, voteSeconds: 1, autoNext: 0 });
  await until(() => G(host).settings.autoNext === 0);
  ok(G(host).settings.askSeconds === 180 && G(host).settings.voteSeconds === 10, 'settings are clamped');
  host.emit('host:truths:settings', { askSeconds: 30, voteSeconds: 60 });
  host.emit('host:truths:start');
  await until(() => G(host).status === 'telling');
  ok(G(host).totalTurns === 3, 'three tellers: the players who wrote lines');
  const tellerId = G(host).teller.id;
  const teller = byId[tellerId];
  const idx = Number(tellerId.slice(1));
  ok([...G(tv).lines].sort().join() === [...lines(idx)].sort().join(), 'the TV shows the teller\'s three lines');
  ok(G(tv).lieAt === null && G(host).lieAt === null && P.filter(s => s !== teller).every(s => G(s).lieAt === null), 'nobody but the teller knows which is the lie');
  ok(G(teller).lieAt !== null && G(tv).lines[G(teller).lieAt] === lines(idx)[[2, 0, 1][idx]], 'the teller\'s phone marks their lie');
  a.emit('player:truths:vote', { index: 0 });
  await sleep(200);
  ok(!G(host).voted.length, 'no voting during question time');
  host.emit('host:truths:vote');
  await until(() => G(host).status === 'voting');
  ok(G(host).voters.length === 4 && !G(host).voters.some(v => v.id === tellerId), 'voting: everyone online except the teller');
  const lie = G(teller).lieAt;
  const truth = (lie + 1) % 3;
  const voters = P.filter(s => s !== teller);
  teller.emit('player:truths:vote', { index: lie });
  voters[0].emit('player:truths:vote', { index: 7 });
  voters[0].emit('player:truths:vote', { index: '1x' });
  await sleep(200);
  ok(!G(host).voted.length, 'the teller can\'t vote; a bad index is ignored');
  voters[0].emit('player:truths:vote', { index: truth });
  voters[0].emit('player:truths:vote', { index: lie });
  voters[1].emit('player:truths:vote', { index: lie });
  voters[2].emit('player:truths:vote', { index: truth });
  await until(() => G(host).voted.length === 3);
  ok(G(voters[0]).myVote === lie && G(tv).myVote === null, 'a vote can be changed; it stays secret (TV gets no votes)');
  ok(G(host).status === 'voting', 'not everyone has voted yet: still voting');
  voters[3].emit('player:truths:vote', { index: truth });
  ok(await until(() => G(tv).status === 'reveal', 3000), 'everyone voted: reveal');
  ok(G(tv).lieAt === lie && G(tv).result.caught === 2 && G(tv).result.fooled === 2 && !G(tv).result.perfect, 'reveal: the lie, 2 caught it, 2 fooled');
  const pts = Object.fromEntries(G(tv).standings.map(r => [r.id, r.points]));
  ok(pts[tellerId] === 2 && pts[voters[0].last.me.id] === 1 && pts[voters[1].last.me.id] === 1 && !pts[voters[2].last.me.id], 'catchers +1, the teller +1 per fooled voter');
  ok(G(tv).result.byLine[lie].length === 2, 'the TV shows who voted for what');
  ok(!G(teller).mySet && G(teller).iTold, 'the teller\'s lines are used up');

  console.log('\n# a perfect lie, a late writer, skipping');
  d.emit('player:truths:write', { lines: lines(3), lie: 1 });
  await until(() => G(host).totalTurns === 4);
  ok(G(host).totalTurns === 4, 'someone who writes during the game gets a turn too');
  teller.emit('player:truths:write', { lines: ['a', 'b', 'c'], lie: 0 });
  await sleep(200);
  ok(G(host).totalTurns === 4, 'but not someone who already told this game');
  host.emit('host:truths:next');
  await until(() => G(host).status === 'telling' && G(host).teller.id !== tellerId);
  const t2 = byId[G(host).teller.id];
  host.emit('host:truths:vote');
  await until(() => G(host).status === 'voting');
  const lie2 = G(t2).lieAt;
  const before2 = (G(host).standings.find(r => r.id === t2.last.me.id) || { points: 0 }).points;
  for (const s of P.filter(x => x !== t2)) s.emit('player:truths:vote', { index: (lie2 + 1) % 3 });
  ok(await until(() => G(tv).status === 'reveal', 3000), 'reveal');
  ok(G(tv).result.perfect && G(tv).result.fooled === 4, 'everyone fooled: a perfect lie');
  ok(G(tv).standings.find(r => r.id === t2.last.me.id).points - before2 === 5, 'perfect lie: +4 fooled, +1 bonus');
  host.emit('host:truths:next');
  await until(() => G(host).status === 'telling' && G(host).turnNo === 3);
  const t3 = G(host).teller.id;
  host.emit('host:truths:skip');
  await until(() => G(host).teller && G(host).teller.id !== t3);
  ok(G(host).turnNo === 3 && G(host).totalTurns === 3, 'skip: the next teller, one turn fewer');
  ok(G(byId[t3]).mySet, 'a skipped teller keeps their lines for another game');
  const t4 = G(host).teller.id;
  host.emit('host:removePlayer', { id: t4 });
  ok(await until(() => G(host).status === 'final' || (G(host).teller && G(host).teller.id !== t4)), 'the teller removed mid-turn: the game moves on');

  console.log('\n# the end');
  if (G(host).status !== 'final') host.emit('host:truths:end');
  ok(await until(() => G(tv).status === 'final'), 'final');
  const aw = G(tv).awards;
  ok(aw && aw.liar && aw.liar.names.length && aw.detector, 'awards: best liar and lie detector');
  ok(aw.liar.n === 4, 'best liar fooled 4');
  host.emit('host:truths:newGame');
  await until(() => G(host).status === 'lobby');
  ok(G(byId[t3]).mySet && !G(t2).mySet && G(teller).mySet, 'new game: unused and freshly written lines stay, told ones are gone');
  host.emit('host:hub:select', { game: 'hub' });
  ok(await until(() => tv.last.activeGame === 'hub' && tv.last.hub.trophies.some(x => x.game === 'truths')), 'the winner goes on the trophy shelf');

  console.log(`\n${pass} passed, ${fail} failed`);
  [host, tv, ...P].forEach(s => s.close());
  process.exit(fail ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
